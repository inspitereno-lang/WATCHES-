async function syncAll() {
  console.log('========================================================================');
  console.log('🚀 SYNCING 13 BHAVANA WATCHES DIRECTLY TO LIVE SITE (dubaiwatchesgallery.com)');
  console.log('========================================================================\n');

  // 1. Fetch current live products to prevent duplicates
  const liveRes = await fetch(`${API_BASE}/products?limit=500`);
  const liveData = await liveRes.json();
  const existingProducts = liveData.products || [];
  console.log(`✓ Fetched ${existingProducts.length} live products currently on storefront.\n`);

  const results = [];

  for (const watch of WATCH_DATA) {
    const trackingTag = `Folder: Watch ${watch.folderNum} / BHAVANA_WATCHES_201026`;
    
    // Check if watch exists on live by tracking tag or exact name
    const existing = existingProducts.find(p => 
      (p.features && p.features.includes(trackingTag)) ||
      p.name === watch.name
    );

    const payload = {
      name: watch.name,
      brand: watch.brand,
      audience: watch.audience,
      factory: watch.factory,
      priceUSD: watch.priceUSD,
      priceAED: watch.priceAED,
      url: '',
      image: watch.image,
      thumbnail: watch.thumbnail,
      images: watch.images,
      movement: watch.movement,
      casing: watch.casing,
      bezel: watch.bezel,
      glass: watch.glass,
      waterResistance: watch.waterResistance,
      description: watch.description,
      features: watch.features,
      inStock: true,
      isVisible: true,
      model: watch.model,
      reference: watch.reference,
      material: watch.material,
      size: watch.size,
      caliber: watch.caliber,
      warranty: watch.warranty,
      nameAr: watch.nameAr,
      brandAr: watch.brandAr,
      modelAr: watch.modelAr,
      materialAr: watch.materialAr,
      movementAr: watch.movementAr,
      casingAr: watch.casingAr,
      bezelAr: watch.bezelAr,
      glassAr: watch.glassAr,
      waterResistanceAr: watch.waterResistanceAr,
      warrantyAr: watch.warrantyAr,
      descriptionAr: watch.descriptionAr
    };

    let savedProduct;
    if (existing) {
      console.log(`[UPDATE] Watch ${watch.folderNum} exists with live ID ${existing.id}: "${watch.name}"`);
      const updateRes = await fetch(`${API_BASE}/products/${existing.id}`, {
        method: 'PUT',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${token}`
        },
        body: JSON.stringify(payload)
      });
      const updateData = await updateRes.json();
      if (!updateRes.ok) {
        throw new Error(`Failed to update live watch ${existing.id}: ${JSON.stringify(updateData)}`);
      }
      savedProduct = updateData.product || existing;
      console.log(`  ✓ Updated live product ID ${savedProduct.id}`);
    } else {
      console.log(`[CREATE] Adding Watch ${watch.folderNum}: "${watch.name}"...`);
      const createRes = await fetch(`${API_BASE}/products`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${token}`
        },
        body: JSON.stringify(payload)
      });
      const createData = await createRes.json();
      if (!createRes.ok) {
        throw new Error(`Failed to create live watch: ${JSON.stringify(createData)}`);
      }
      savedProduct = createData.product;
      console.log(`  ✓ Created live product ID ${savedProduct.id}`);
    }

    results.push({
      id: savedProduct.id,
      name: savedProduct.name,
      reference: savedProduct.reference,
      priceUSD: savedProduct.priceUSD,
      priceAED: savedProduct.priceAED,
      liveUrl: `https://dubaiwatchesgallery.com/watches/${savedProduct.id}`
    });
  }

  console.log('\n========================================================================');
  console.log('✅ ALL 13 WATCHES ARE NOW FULLY LIVE ON DUBAIWATCHESGALLERY.COM');
  console.log('========================================================================');
  console.table(results);
}

syncAll().catch(err => {
  console.error('Fatal error during live sync:', err);
  process.exit(1);
});
